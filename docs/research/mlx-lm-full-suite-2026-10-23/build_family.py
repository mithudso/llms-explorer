#!/usr/bin/env python3
"""Regenerate this suite's navigation through the existing family compiler."""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path


def build(root: Path, members: list[dict], summary: str, export_llms) -> dict:
    original = export_llms.mirror_io.load_json
    manifests = {}
    for member in members:
        directory = root / f"{member['slug']}.llms"
        manifest = json.loads((directory / "manifest.json").read_text())
        units = [json.loads(line) for line in (directory / "units.jsonl").read_text().splitlines() if line]
        if manifest.get("research_status") != "COMPLETED":
            raise ValueError(f"Incomplete member: {member['slug']}")
        if not units or any(unit.get("validation_status") != "SUPPORTED" for unit in units):
            raise ValueError(f"Member lacks an all-claim gate: {member['slug']}")
        urls = {url for unit in units
                for url in [unit.get("source_url") or unit.get("url"), *unit.get("also", [])]
                if isinstance(url, str) and url.startswith(("https://", "http://"))}
        manifests[str(directory / "manifest.json")] = {
            **manifest, "title": member.get("label", manifest["concept"]), "pages": len(urls), "units": len(units),
        }

    def adapted(path, default=None):
        return manifests.get(str(path), original(path, default=default))

    directory = root / "mlx-lm-family.llms"
    directory.mkdir(exist_ok=True)
    export_llms.mirror_io.load_json = adapted
    try:
        result = export_llms.family(
            [root / f"{member['slug']}.md" for member in members],
            "MLX-LM concept family", summary, directory / "llms.txt", base_url="..",
        )
    finally:
        export_llms.mirror_io.load_json = original
    if result["products"] != len(members):
        raise ValueError("Family compiler omitted a member")
    index_path = directory / "llms.txt"
    text = index_path.read_text()
    banner = "<!-- Generated by docset_refine.family; verified-as-of: 2026-10-23 -->"
    text = text.replace("\n\n>", "\n\n" + banner + "\n\n>", 1)
    index_path.write_text(text)
    content = index_path.read_bytes()
    manifest = {
        "kind": "family", "subject": "MLX-LM", "generator": "docset_refine.family",
        "members": members, "index_sha256": hashlib.sha256(content).hexdigest(),
        "files": {"llms.txt": {"bytes": len(content), "tokens": export_llms._tokens(content.decode())}},
        "counts": "pages count distinct cited URLs; units count authored supported statements",
        "semantic_index": "deferred while embeddings are paused",
    }
    (directory / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return {"members": len(members), "index_sha256": manifest["index_sha256"]}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--hub", type=Path, default=Path.home() / ".global-ai-hub")
    parser.add_argument("--members", type=Path, required=True)
    parser.add_argument("--summary", required=True)
    args = parser.parse_args()
    sys.path.insert(0, str(args.repo / "hub/scripts"))
    from docset_refine import export_llms

    members = json.loads(args.members.read_text())
    reports = {}
    for label, root in (("hub", args.hub / "llms-concepts"),
                        ("repository", args.repo / "outputs/llms-concepts")):
        reports[label] = build(root, members, args.summary, export_llms)
    print(json.dumps(reports, indent=2))


if __name__ == "__main__":
    main()
